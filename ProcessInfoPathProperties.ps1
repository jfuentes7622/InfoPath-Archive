<#
.SYNOPSIS
	Extracts normalized properties from InfoPath XML files into multiple CSVs using version-specific structure configs.

.DESCRIPTION
	Reads InfoPath XML files and normalizes data into multiple tables (Main + repeating groups)
	based on structure metadata from ProcessInfoPathAnalyze.ps1.

	Completely generic—no assumptions about document type or element names. Data structure
	is driven by StructureReport_[Version].json files generated by the analyzer.

	Supports two modes:
	  1. Version-aware extraction: Uses VersioningCsvPath + AnalysisDirectory to load version-specific configs
	  2. Single-config extraction: Uses StructureConfigPath for all files
	  3. Auto-analysis (fallback): Analyzes source files if no config provided

	Outputs to OutputDirectory/Normalized/:
	  - Main.csv: Non-repeating fields
	  - <GroupName>.csv: One CSV per repeating group detected
	  - PropertyMapping.csv: Mapping of shortened names to original XPaths
	  - ProcessingReport.txt: Statistics and diagnostics

.PARAMETER SourceDirectory
	Root folder containing InfoPath XML files to extract.

.PARAMETER OutputDirectory
	Directory where normalized CSVs will be written (output goes to Normalized/ subdirectory).

.PARAMETER VersioningCsvPath
	(Optional) Path to versioning CSV from ClassifyInfoPathVersions.ps1.
	Must have columns: TemplateVersion/TemplateName and SourceFilePath/FileName.
	If provided with AnalysisDirectory, enables version-based config loading.

.PARAMETER AnalysisDirectory
	(Optional) Directory containing version-specific StructureReport_[Version].json files.
	Required when using VersioningCsvPath. Created by ProcessInfoPathAnalyze.ps1 with versioning.

.PARAMETER StructureConfigPath
	(Optional) Path to single StructureReport.json for all files.
	Ignored if VersioningCsvPath + AnalysisDirectory provided.
	If omitted, runs auto-analysis on source files (slower, one-time cost).

.PARAMETER Recurse
	Include subfolders when discovering XML files.

.EXAMPLE
	# Version-based extraction (recommended for multi-version documents)
	.\ProcessInfoPathAnalyze.ps1 `
	  -SourceDirectory "C:\Samples" `
	  -OutputDirectory "C:\Analysis" `
	  -VersioningCsvPath "C:\Reports\InfoPathVersionMap.csv"

	.\ProcessInfoPathProperties.ps1 `
	  -SourceDirectory "C:\AllDocuments" `
	  -OutputDirectory "C:\Reports" `
	  -VersioningCsvPath "C:\Reports\InfoPathVersionMap.csv" `
	  -AnalysisDirectory "C:\Analysis"

.EXAMPLE
	# Single-config extraction (all files use same structure)
	.\ProcessInfoPathProperties.ps1 `
	  -SourceDirectory "C:\AllDocuments" `
	  -OutputDirectory "C:\Reports" `
	  -StructureConfigPath "C:\Analysis\StructureReport.json"

.EXAMPLE
	# Quick extraction without separate analysis (auto-detects structure)
	.\ProcessInfoPathProperties.ps1 `
	  -SourceDirectory "C:\AllDocuments" `
	  -OutputDirectory "C:\Reports" `
	  -Recurse

.NOTES
	Generic extraction pipeline—works on any InfoPath document type.
	For multi-version documents, use VersioningCsvPath + AnalysisDirectory for version-specific handling.
	For single document type, use -StructureConfigPath for optimal performance.
#>

[CmdletBinding()]
param(
	# Folder that contains InfoPath XML files.
	[Parameter(Mandatory = $true)]
	[ValidateNotNullOrEmpty()]
	[string]$SourceDirectory,

	# Output directory where normalized CSVs will be written.
	[Parameter(Mandatory = $true)]
	[ValidateNotNullOrEmpty()]
	[string]$OutputDirectory,

	# (Optional) Path to versioning CSV from ClassifyInfoPathVersions.ps1
	[string]$VersioningCsvPath = $null,

	# (Optional) Directory containing version-specific StructureReport_[Version].json files
	[string]$AnalysisDirectory = $null,

	# (Optional) Path to StructureReport.json from analyzer (used if versioning not provided)
	[string]$StructureConfigPath = $null,

	# Include subfolders when searching for XML files.
	[switch]$Recurse
)

Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"

function Write-Stage {
	param(
		[Parameter(Mandatory = $true)]
		[string]$Message,

		[ValidateSet("Init", "Input", "Parse", "Extract", "Map", "Write", "Done", "Warn", "Error")]
		[string]$Group = "Parse"
	)

	$color = switch ($Group) {
		"Init" { "Cyan" }
		"Input" { "DarkCyan" }
		"Parse" { "Yellow" }
		"Extract" { "Gray" }
		"Map" { "Blue" }
		"Write" { "Green" }
		"Done" { "Magenta" }
		"Warn" { "DarkYellow" }
		"Error" { "Red" }
		default { "White" }
	}

	Write-Host "[$Group] $Message" -ForegroundColor $color
}

# Build version index from versioning CSV
function New-VersionIndex {
	param(
		[Parameter(Mandatory = $true)]
		[object[]]$VersionRows
	)

	$index = @{}
	foreach ($row in $VersionRows) {
		$version = $null
		$filePath = $null

		# Find version column
		foreach ($col in @("TemplateVersion", "TemplateName", "Version", "Group")) {
			if ($null -ne $row.$col -and -not [string]::IsNullOrWhiteSpace($row.$col)) {
				$version = $row.$col
				break
			}
		}

		# Find filepath column
		foreach ($col in @("SourceFilePath", "FilePath", "FileName", "Name")) {
			if ($null -ne $row.$col -and -not [string]::IsNullOrWhiteSpace($row.$col)) {
				$filePath = $row.$col
				break
			}
		}

		if ($null -ne $version -and -not [string]::IsNullOrWhiteSpace($filePath)) {
			$fileName = [System.IO.Path]::GetFileName($filePath)
			$key = $fileName.ToLowerInvariant()
			$index[$key] = $version
		}
	}

	return $index
}

# Resolve a file's version from the version index
function Resolve-FileVersion {
	param(
		[Parameter(Mandatory = $true)]
		[System.IO.FileInfo]$XmlFile,

		[Parameter(Mandatory = $true)]
		[hashtable]$VersionIndex
	)

	$key = $XmlFile.Name.ToLowerInvariant()
	return $VersionIndex[$key]
}

