}

function Try-DecodeInfoPathAttachment {
	param(
		[Parameter(Mandatory = $true)]
		[AllowEmptyString()]
		[string]$Value
	)

	if ([string]::IsNullOrWhiteSpace($Value)) {
		return $null
	}

	$candidate = $Value.Trim()
	if ($candidate.Length -lt 64 -or ($candidate -notmatch '^[A-Za-z0-9+/=\r\n]+$')) {
		return $null
	}

	try {
		$bytes = [System.Convert]::FromBase64String($candidate)
	}
	catch {
		return $null
	}

	if ($bytes.Length -lt 28) {
		return $null
	}

	if ($bytes[0] -ne 0xC7 -or $bytes[1] -ne 0x49 -or $bytes[2] -ne 0x46 -or $bytes[3] -ne 0x41) {
		return $null
	}

	$stream = [System.IO.MemoryStream]::new($bytes)
	$reader = [System.IO.BinaryReader]::new($stream)

	try {
		$null = $reader.ReadBytes(16)
		$fileSize = $reader.ReadUInt32()
		$fileNameCharacterCount = $reader.ReadUInt32()

		if ($fileNameCharacterCount -lt 1 -or $fileNameCharacterCount -gt [int]::MaxValue / 2) {
			return $null
		}

		$fileNameByteLength = [int]$fileNameCharacterCount * 2
		if ($fileNameByteLength -gt ($bytes.Length - 24)) {
			return $null
		}

		$fileNameBytes = $reader.ReadBytes($fileNameByteLength)
		if ($fileNameBytes.Length -lt $fileNameByteLength) {
			return $null
		}

		$decodedName = [System.Text.Encoding]::Unicode.GetString($fileNameBytes)
		$decodedName = $decodedName.Trim([char]0)
		if ([string]::IsNullOrWhiteSpace($decodedName)) {
			$decodedName = 'attachment.bin'
		}

		$remaining = [int]($stream.Length - $stream.Position)
		if ($remaining -le 0) {
			return $null
		}

		$bytesToRead = [Math]::Min([int]$fileSize, $remaining)
		if ($bytesToRead -le 0) {
			$bytesToRead = $remaining
		}

		$fileBytes = $reader.ReadBytes($bytesToRead)
		if ($fileBytes.Length -eq 0) {
			return $null
		}

		return @{
			FileName = [System.IO.Path]::GetFileName($decodedName)
			Content  = $fileBytes
		}
	}
	catch {
		return $null
	}
	finally {
		$reader.Dispose()
		$stream.Dispose()
	}
}

function New-UniqueAttachmentPath {
	param(
		[Parameter(Mandatory = $true)]
		[string]$DirectoryPath,
		[Parameter(Mandatory = $true)]
		[string]$DesiredName
	)

	$baseName = [System.IO.Path]::GetFileNameWithoutExtension($DesiredName)
	$extension = [System.IO.Path]::GetExtension($DesiredName)
	if ([string]::IsNullOrWhiteSpace($extension)) {
		$extension = '.bin'
	}

	$safeBase = Convert-ToSafeFileName -Value $baseName
	$candidate = Join-Path -Path $DirectoryPath -ChildPath ($safeBase + $extension)
	$counter = 1

	while (Test-Path -LiteralPath $candidate -PathType Leaf) {
		$candidate = Join-Path -Path $DirectoryPath -ChildPath ("{0}_{1}{2}" -f $safeBase, $counter, $extension)
		$counter++
	}

	return $candidate
}

function Expand-EmbeddedAttachments {
	param(
		[Parameter(Mandatory = $true)]
		[System.Xml.XmlNode]$Node,
		[Parameter(Mandatory = $true)]
		[string]$CurrentPath,
		[Parameter(Mandatory = $true)]
		[string]$AttachmentOutputDirectory,
		[Parameter(Mandatory = $true)]
		[string]$RelativePrefix
	)

	if (Test-HtmlFormattingNode -Node $Node) {
		return 0
	}

	$extractedCount = 0

	$children = Get-NodeChildElements -Node $Node
	if ($children.Count -eq 0) {
		$decodedAttachment = Try-DecodeInfoPathAttachment -Value $Node.InnerText
		if ($null -eq $decodedAttachment) {
			return 0
		}

		$desiredName = if ([string]::IsNullOrWhiteSpace($decodedAttachment.FileName)) { 'attachment.bin' } else { $decodedAttachment.FileName }
		$targetFilePath = New-UniqueAttachmentPath -DirectoryPath $AttachmentOutputDirectory -DesiredName $desiredName
		[System.IO.File]::WriteAllBytes($targetFilePath, $decodedAttachment.Content)

		$fileName = [System.IO.Path]::GetFileName($targetFilePath)
		$relativePath = "{0}/{1}" -f $RelativePrefix.TrimEnd('/'), $fileName
		$Node.InnerText = "ATTACHMENT::$relativePath"
		return 1
	}

	$nameCounts = @{}
	foreach ($child in $children) {
		$childName = $child.get_Name()
		if ($nameCounts.ContainsKey($childName)) {
			$nameCounts[$childName]++
		}
		else {
			$nameCounts[$childName] = 1
		}
	}

	$nameIndexes = @{}
	foreach ($child in $children) {
		$childName = $child.get_Name()
		if ($nameIndexes.ContainsKey($childName)) {
			$nameIndexes[$childName]++
		}
		else {
			$nameIndexes[$childName] = 1
		}

		$childPath = "$CurrentPath/$childName"
		if ($nameCounts[$childName] -gt 1) {
			$childPath = "$childPath[$($nameIndexes[$childName])]"
		}

		$extractedCount += Expand-EmbeddedAttachments -Node $child -CurrentPath $childPath -AttachmentOutputDirectory $AttachmentOutputDirectory -RelativePrefix $RelativePrefix
	}

	return $extractedCount
}

