<#
.SYNOPSIS
	Transforms InfoPath XML files into HTML, optionally PDF, using group-specific XSLT templates.

.DESCRIPTION
	Processes InfoPath XML files from a source directory and transforms each file to HTML using
	the XSLT template resolved from the grouping CSV and template-mapping CSV produced by the
	newer InfoPath analysis pipeline. Optionally prints the generated HTML to PDF using Edge or Chrome.

.PARAMETER InfoPathDirectory
	Root folder containing InfoPath XML files to process.

.PARAMETER MetadataCsvPath
	Path to the metadata CSV used to inject metadata values into XSLT parameters.

.PARAMETER GroupingCsvPath
	Path to the detailed grouping CSV generated by AnalyzeInfoPathGroupingFromCsv.ps1.
	This file is used to resolve SuggestedGroup for each InfoPath XML file.

.PARAMETER TemplateMappingCsvPath
	Path to the template mapping CSV generated by BuildXsltFromGroupingCsv.ps1.
	This file maps SuggestedGroup to the correct XSLT/CSS assets.

.PARAMETER OutputDirectory
	Destination root folder for generated HTML files and copied CSS assets.

.PARAMETER PrintToPdf
	String true/false style parameter controlling PDF generation.
	Accepted values: yes, no, true, false, 1, 0.
	Default: false

.PARAMETER ErrorLogPath
	Optional path for the processing error log file.
	If omitted, a default log file is created in the output directory.

.PARAMETER FailedFilesDirectory
	Optional folder where failed XML files are copied for review.
	If omitted, a default folder is created under the output directory.

.PARAMETER Recurse
	Include subfolders when discovering XML files to process.

.PARAMETER UseDisplayName
	Prefer matched XSN captions, falling back to readable XML-name labels. Set to $false for exact
	internal XML names. Requires templates generated with label-mode support.
	Default: $true.

.PARAMETER DateFormat
	Legacy standalone override for JSON DateFormat. Prefer FieldRulesPath.
	.NET format for ISO date-only field values displayed in HTML.
	Formatting uses invariant culture and preserves the source date/time offset.
	Only the in-memory rendering document changes; source XML, CSVs, and metadata
	are unchanged. Default: MM/dd/yyyy.

.PARAMETER DateTimeFormat
	Legacy standalone override for JSON DateTimeFormat. Prefer FieldRulesPath.
	.NET format for ISO date/time values. Default: MM/dd/yyyy HH:mm.
	Stored clock times and offsets are retained without local-time conversion.

.PARAMETER FieldRulesPath
	Optional JSON field definitions and stored/display mappings for HTML only.
	Use the same definitions when building templates.

.PARAMETER ReferenceDataPath
	Optional offline SPS reference-data folder or Manifest.json for lookup labels
	and user names in either HTML renderer. Unresolved values remain unchanged
	and are reported in InfoPathReferenceResolutions.csv. No SharePoint calls.

.PARAMETER XsnInventoryCsvPath
	Optional processed XSN inventory. Matches each file to its same-form exact
	solutionVersion or nearest higher version and applies available XSN captions
	when UseDisplayName is true. Writes InfoPathXsnMatches.csv under OutputDirectory.

.PARAMETER UseXSN4HTML
	Prefer the exact-version XSN view, otherwise the nearest higher version of the
	same form, for static archival HTML. Missing or unsupported
	views fall back to generated HTML with a warning and an audit reason. Default: $false.

.EXAMPLE
	.\ProcessInfopathToHTML.ps1 `
	  -InfoPathDirectory "C:\Temp\RedApps" `
	  -MetadataCsvPath "C:\Temp\Reports\InfoPathVersionMap.csv" `
	  -GroupingCsvPath "C:\Temp\Reports\InfoPathGroupingDetailed.csv" `
	  -TemplateMappingCsvPath "C:\Temp\Templates\InfoPathXsltGroupMap.csv" `
	  -OutputDirectory "C:\Temp\HtmlOutput" `
	  -Recurse

.EXAMPLE
	.\ProcessInfopathToHTML.ps1 `
	  -InfoPathDirectory "C:\Temp\RedApps" `
	  -MetadataCsvPath "C:\Temp\Reports\InfoPathVersionMap.csv" `
	  -GroupingCsvPath "C:\Temp\Reports\InfoPathGroupingDetailed.csv" `
	  -TemplateMappingCsvPath "C:\Temp\Templates\InfoPathXsltGroupMap.csv" `
	  -OutputDirectory "C:\Temp\HtmlOutput" `
	  -PrintToPdf "true"

.NOTES
	Requires the prior pipeline outputs from:
	- ClassifyInfoPathVersions.ps1
	- AnalyzeInfoPathGroupingFromCsv.ps1
	- BuildXsltFromGroupingCsv.ps1
#>

