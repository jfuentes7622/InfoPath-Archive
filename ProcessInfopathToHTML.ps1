Write-Stage -Group Input -Message "InfoPath directory: $InfoPathDirectory"
Write-Stage -Group Input -Message "Metadata CSV: $MetadataCsvPath"
Write-Stage -Group Input -Message "Grouping CSV: $GroupingCsvPath"
Write-Stage -Group Input -Message "Template mapping CSV: $TemplateMappingCsvPath"
Write-Stage -Group Input -Message "Output directory: $OutputDirectory"
Write-Stage -Group Input -Message "HTML date format: $DateFormat"
Write-Stage -Group Input -Message "HTML date/time format: $DateTimeFormat"

if (-not (Test-Path -LiteralPath $MetadataCsvPath -PathType Leaf)) {
	throw "MetadataCsvPath does not exist: $MetadataCsvPath"
}

if (-not (Test-Path -LiteralPath $GroupingCsvPath -PathType Leaf)) {
	throw "GroupingCsvPath does not exist: $GroupingCsvPath"
}

if (-not (Test-Path -LiteralPath $TemplateMappingCsvPath -PathType Leaf)) {
	throw "TemplateMappingCsvPath does not exist: $TemplateMappingCsvPath"
}

if (-not (Test-Path -LiteralPath $OutputDirectory -PathType Container)) {
	New-Item -Path $OutputDirectory -ItemType Directory -Force | Out-Null
}

if ([string]::IsNullOrWhiteSpace($ErrorLogPath)) {
	$ErrorLogPath = Join-Path -Path $OutputDirectory -ChildPath "ProcessInfopathToHTML-errors.log"
}

if ([string]::IsNullOrWhiteSpace($FailedFilesDirectory)) {
	$FailedFilesDirectory = Join-Path -Path $OutputDirectory -ChildPath "FailedInfoPathFiles"
}

if (-not (Test-Path -LiteralPath $FailedFilesDirectory -PathType Container)) {
	New-Item -Path $FailedFilesDirectory -ItemType Directory -Force | Out-Null
}

$errorLogDirectory = Split-Path -Path $ErrorLogPath -Parent
if (-not [string]::IsNullOrWhiteSpace($errorLogDirectory) -and -not (Test-Path -LiteralPath $errorLogDirectory -PathType Container)) {
	New-Item -Path $errorLogDirectory -ItemType Directory -Force | Out-Null
}

$shouldPrintPdf = Convert-ToBooleanValue -Value $PrintToPdf -ParameterName "PrintToPdf"
$pdfBrowser = $null
if ($shouldPrintPdf) {
	$pdfBrowser = Find-PdfBrowser
	if ($null -eq $pdfBrowser) {
		throw "PrintToPdf was enabled, but no supported browser was found (Microsoft Edge or Google Chrome)."
	}
}

$metadataRows = @(Import-Csv -LiteralPath $MetadataCsvPath)
$metadataIndex = New-MetadataIndex -Rows $metadataRows
$groupingRows = @(Import-Csv -LiteralPath $GroupingCsvPath)
$groupingIndex = New-FileRowIndex -Rows $groupingRows
$templateMappingRows = @(Import-Csv -LiteralPath $TemplateMappingCsvPath)
$templateMappingIndex = New-TemplateMappingIndex -Rows $templateMappingRows
$xsltCache = @{}
$xsnViewCache = @{}

Write-Stage -Group Input -Message "Loaded metadata rows: $($metadataRows.Count)"
Write-Stage -Group Input -Message "Loaded grouping rows: $($groupingRows.Count)"
Write-Stage -Group Input -Message "Loaded template mapping rows: $($templateMappingRows.Count)"

# Diagnostic: Show which SuggestedGroups are available in the template mapping
Write-Stage -Group Input -Message "Available SuggestedGroups in template mapping:"
foreach ($suggestedGroup in @($templateMappingIndex.Keys | Sort-Object)) {
	$row = $templateMappingIndex[$suggestedGroup]
	$xsltPath = [string]$row.XsltPath
	$fileExists = if ([string]::IsNullOrWhiteSpace($xsltPath)) { "EMPTY" } elseif (Test-Path -LiteralPath $xsltPath -PathType Leaf) { "EXISTS" } else { "MISSING" }
	Write-Stage -Group Input -Message "  - Group: $suggestedGroup | XsltPath: $xsltPath | Status: $fileExists"
}

$searchParameters = @{
	LiteralPath = $InfoPathDirectory
	Filter      = "*.xml"
	File        = $true
}

if ($Recurse.IsPresent) {
	$searchParameters.Recurse = $true
}

$xmlFiles = @(Get-ChildItem @searchParameters)
if ($xmlFiles.Count -eq 0) {
	throw "No XML files were found in: $InfoPathDirectory"
}

Write-Stage -Group Input -Message "Discovered XML files: $($xmlFiles.Count)"

$processedCount = 0
$xsnMatches = [System.Collections.Generic.List[object]]::new()
$referenceAuditPath = [System.IO.Path]::GetFullPath((Join-Path $OutputDirectory 'InfoPathReferenceResolutions.csv'))
'"SourceFilePath","XPath","StoredValue","DisplayValue","Status","Source","ReferenceKey","Message"' | Set-Content -LiteralPath $referenceAuditPath -Encoding UTF8
Write-Stage -Group Input -Message "Reference-resolution audit: $referenceAuditPath"
$pdfCount = 0
$failedCount = 0
$errorLogEntries = New-Object System.Collections.Generic.List[string]

foreach ($xmlFile in $xmlFiles) {
	$matchRow = [pscustomobject][ordered]@{
		SourceFilePath = $xmlFile.FullName
		RequestedVersion = ''
		SourceSolutionName = ''
		SourceTemplateHref = ''
		MatchStatus = 'NotProcessed'
		MatchBasis = ''
		LinkedTemplateVersions = ''
		MatchedVersion = ''
		MatchedSolutionName = ''
		MatchedTemplateUrl = ''
		MatchedXsnPath = ''
		MatchedLabelsPath = ''
		AppliedLabelCount = 0
		Message = ''
		Error = ''
		RequestedRenderer = $(if ($UseXSN4HTML) { 'XSN' } else { 'Generated' })
		ActualRenderer = ''
		ViewName = ''
		FallbackReason = ''
		HtmlPath = ''
		PdfPath = ''
	}
	$xsnMatches.Add($matchRow)
	try {
		Write-Stage -Group Build -Message "Processing file: $($xmlFile.FullName)"

		$relativePath = Get-RelativePath -BasePath $InfoPathDirectory -FullPath $xmlFile.FullName
		$relativeDirectory = Split-Path -Path $relativePath -Parent

		$destinationDirectory = if ([string]::IsNullOrWhiteSpace($relativeDirectory)) {
			$OutputDirectory
		}
		else {
			Join-Path -Path $OutputDirectory -ChildPath $relativeDirectory
		}

		if (-not (Test-Path -LiteralPath $destinationDirectory -PathType Container)) {
			New-Item -Path $destinationDirectory -ItemType Directory -Force | Out-Null
		}

		$baseName = [System.IO.Path]::GetFileNameWithoutExtension($xmlFile.Name)
		$htmlOutputPath = Join-Path -Path $destinationDirectory -ChildPath "$baseName.html"
		$pdfOutputPath = Join-Path -Path $destinationDirectory -ChildPath "$baseName.pdf"
		$attachmentDirectoryName = "{0}_attachments" -f (Convert-ToSafeFileName -Value $baseName)
		$attachmentOutputDirectory = Join-Path -Path $destinationDirectory -ChildPath $attachmentDirectoryName
		if (-not (Test-Path -LiteralPath $attachmentOutputDirectory -PathType Container)) {
			New-Item -Path $attachmentOutputDirectory -ItemType Directory -Force | Out-Null
		}

		$metadataRow = Resolve-MetadataRow -XmlFile $xmlFile -MetadataIndex $metadataIndex
		$groupingRow = Resolve-IndexedFileRow -XmlFile $xmlFile -Index $groupingIndex
		if ($null -eq $groupingRow) {
			throw "No grouping row was found for '$($xmlFile.FullName)'."
		}

		$suggestedGroup = [string]$groupingRow.SuggestedGroup
		Write-Stage -Group Resolve -Message "Resolved SuggestedGroup '$suggestedGroup' for file '$($xmlFile.Name)'."
		if ([string]::IsNullOrWhiteSpace($suggestedGroup) -or $suggestedGroup -eq 'ParseFailed') {
			throw "File '$($xmlFile.FullName)' does not have a usable SuggestedGroup."
		}

		# Load into XmlDocument first so embedded attachment payloads can be decoded and replaced with file references.
		$xmlSettings = [System.Xml.XmlReaderSettings]::new()
		$xmlSettings.IgnoreComments = $true
		$xmlSettings.IgnoreWhitespace = $false
		$xmlSettings.DtdProcessing = [System.Xml.DtdProcessing]::Prohibit
		$xmlDocument = [System.Xml.XmlDocument]::new()
		$xmlDocument.XmlResolver = $null
		$xmlDocument.PreserveWhitespace = $true
		$streamReader = [System.IO.StreamReader]::new($xmlFile.FullName, $true)
		$rawXml = $streamReader.ReadToEnd()
		$streamReader.Dispose()
		$xmlReaderForLoad = [System.Xml.XmlReader]::Create([System.IO.StringReader]::new($rawXml), $xmlSettings)

		try {
			$xmlDocument.Load($xmlReaderForLoad)
		}
		finally {
			$xmlReaderForLoad.Dispose()
		}

		$attachmentCount = 0
		if ($null -ne $xmlDocument.DocumentElement) {
			$attachmentCount = Expand-EmbeddedAttachments -Node $xmlDocument.DocumentElement -CurrentPath $xmlDocument.DocumentElement.get_Name() -AttachmentOutputDirectory $attachmentOutputDirectory -RelativePrefix $attachmentDirectoryName
		}

		if ($attachmentCount -gt 0) {
			Write-Stage -Group Resolve -Message "Extracted $attachmentCount embedded attachment(s) from '$($xmlFile.Name)'."
		}

		Export-HtmlFieldAttachments -Document $xmlDocument -Configuration $fieldRules -SourceFileDirectory $xmlFile.DirectoryName -SourceRoot $InfoPathDirectory -AttachmentOutputDirectory $attachmentOutputDirectory -RelativePrefix $attachmentDirectoryName
		$xsnMatch = Find-XsnTemplate -Document $xmlDocument -Inventory $xsnInventory
		$referenceResolutions = [System.Collections.Generic.List[object]]::new()
		try {
			Set-HtmlReferenceValues -Document $xmlDocument -ReferenceData $referenceData -Audit $referenceResolutions -SourceFilePath $xmlFile.FullName -XsnMatch $xsnMatch
		}
		finally {
			if ($referenceResolutions.Count -gt 0) {
				$referenceResolutions | Export-Csv -LiteralPath $referenceAuditPath -Append -NoTypeInformation -Encoding UTF8
			}
		}
		$unresolvedReferences = @($referenceResolutions | Where-Object Status -ne 'Resolved')
		if ($unresolvedReferences.Count -gt 0) {
			Write-Stage -Group Warn -Message "$($xmlFile.Name): $($unresolvedReferences.Count) unresolved/ambiguous reference(s); original values retained. See InfoPathReferenceResolutions.csv."
		}
		$xsnDocument = if ($UseXSN4HTML) { $xmlDocument.CloneNode($true) } else { $null }
		Convert-HtmlFieldValues -Document $xmlDocument -Configuration $fieldRules -DateFormat $DateFormat -DateTimeFormat $DateTimeFormat
		$matchRow.RequestedVersion = $xsnMatch.RequestedVersion
		$matchRow.SourceSolutionName = $xsnMatch.SolutionName
		$matchRow.SourceTemplateHref = $xsnMatch.Href
		$matchRow.MatchStatus = $xsnMatch.Status
		$matchRow.MatchBasis = $xsnMatch.MatchBasis
		$matchRow.LinkedTemplateVersions = $xsnMatch.LinkedTemplateVersions
		$matchRow.Message = $xsnMatch.Message
		if ($null -ne $xsnMatch.Template) {
			$matchRow.MatchedVersion = $xsnMatch.Template.Row.SolutionVersion
			$matchRow.MatchedSolutionName = $xsnMatch.Template.Row.SolutionName
			$matchRow.MatchedTemplateUrl = $xsnMatch.Template.Row.TemplateUrl
			$matchRow.MatchedXsnPath = $xsnMatch.Template.Row.XsnPath
			$matchRow.MatchedLabelsPath = $xsnMatch.Template.LabelsPath
		}
		$appliedLabels = Set-XsnDisplayLabels -Document $xmlDocument -Match $xsnMatch
		$matchRow.AppliedLabelCount = if ($UseDisplayName) { $appliedLabels } else { 0 }
		$matchGroup = if ($xsnMatch.Status -in @('NextVersion', 'NoMatch')) { 'Warn' } else { 'Resolve' }
		if ($null -ne $xsnMatch.Template) {
			$matchType = if ($xsnMatch.Status -eq 'NextVersion') { 'next' } else { 'exact' }
			$identityNote = if ($xsnMatch.MatchBasis -eq 'TemplateUrlIdentityFallback') { ' (template URL match; form name differs)' } else { '' }
			Write-Stage -Group $matchGroup -Message "$($xmlFile.Name): Using $matchType XSN match: XML $($xsnMatch.RequestedVersion) -> XSN $($matchRow.MatchedVersion)$identityNote."
		}
		else {
			if ($xsnMatch.LinkedTemplateVersions) {
				Write-Stage -Group Resolve -Message "$($xmlFile.Name): Linked XSN version(s): $($xsnMatch.LinkedTemplateVersions)."
			}
			Write-Stage -Group $matchGroup -Message "$($xmlFile.Name): $($xsnMatch.Message)"
		}

		$renderedWithXsn = $false
		if ($UseXSN4HTML) {
			try {
				if ($xsnMatch.Status -notin @('ExactVersion', 'NextVersion')) {
					throw "No same-form XSN view at the requested version or higher ($($xsnMatch.Status))."
				}
				$template = $xsnMatch.Template
				if ($template.Row.PSObject.Properties.Name -notcontains 'ResourcesRelativePath' -or -not $template.Row.ResourcesRelativePath) {
					throw 'XSN rendering resources are missing. Rerun step 1 with -UseXSN4HTML $true.'
				}
				$manifest = Resolve-XsnLocalResource $template.InventoryRoot ($template.Row.ResourcesRelativePath + '\manifest.xsf')
				$matchRow.ViewName = Write-XsnArchiveHtml -Document $xsnDocument -Configuration $fieldRules -ResourceDirectory (Split-Path $manifest -Parent) -TemplateHash $template.Row.Sha256 -HtmlPath $htmlOutputPath -OutputRoot $OutputDirectory -Cache $xsnViewCache
				$renderedWithXsn = $true
				$matchRow.ActualRenderer = 'XSN'
			}
			catch {
				$matchRow.FallbackReason = $_.Exception.Message
				Write-Stage -Group Warn -Message "XSN rendering fallback for '$($xmlFile.Name)': $($matchRow.FallbackReason)"
				Write-ErrorLogEntry -ErrorLogEntries $errorLogEntries -SourceFile $xmlFile.FullName -Message "XSN fallback: $($matchRow.FallbackReason)"
			}
		}
		if (-not $renderedWithXsn) {
			$templateMapKey = $suggestedGroup.ToLowerInvariant()
			if (-not $templateMappingIndex.ContainsKey($templateMapKey)) {
				throw "No template mapping row was found for SuggestedGroup '$suggestedGroup'."
			}
			$templateMapRow = $templateMappingIndex[$templateMapKey]
			$resolvedXsltPath = [string]$templateMapRow.XsltPath
			if ([string]::IsNullOrWhiteSpace($resolvedXsltPath)) {
				throw "Mapped XSLT path is EMPTY (null/blank) for SuggestedGroup '$suggestedGroup'."
			}
			if (-not (Test-Path -LiteralPath $resolvedXsltPath -PathType Leaf)) {
				throw "XSLT file does not exist: '$resolvedXsltPath'. Check BuildXsltFromGroupingCsv.ps1 output."
			}
			Write-Stage -Group Resolve -Message "Using generated XSLT '$resolvedXsltPath'."
			$resolvedCssPath = [string]$templateMapRow.CssPath
			if (-not [string]::IsNullOrWhiteSpace($resolvedCssPath) -and (Test-Path -LiteralPath $resolvedCssPath -PathType Leaf)) {
				$destinationCssPath = Join-Path $destinationDirectory ([System.IO.Path]::GetFileName($resolvedCssPath))
				if (-not (Test-Path -LiteralPath $destinationCssPath -PathType Leaf)) {
					Copy-Item -LiteralPath $resolvedCssPath -Destination $destinationCssPath -Force
				}
			}
			$xslt = Get-XsltTransformFromCache -XsltPath $resolvedXsltPath -Cache $xsltCache
			$xsltArgs = [System.Xml.Xsl.XsltArgumentList]::new()
			$xsltArgs.AddParam('sourceFilePath', '', $xmlFile.FullName)
			$xsltArgs.AddParam('sourceFileName', '', $xmlFile.Name)
			$xsltArgs.AddParam('templateGroup', '', $suggestedGroup)
			$xsltArgs.AddParam('UseDisplayName', '', $UseDisplayName)
			$xsltArgs.AddParam('UseEmbeddedXsnLabels', '', $false)
			if ($null -ne $metadataRow) {
				foreach ($property in $metadataRow.PSObject.Properties) {
					if (-not [string]::IsNullOrWhiteSpace($property.Name) -and -not [string]::IsNullOrWhiteSpace([string]$property.Value)) {
						$xsltArgs.AddParam((Convert-ToXsltParamName -Name $property.Name), '', [string]$property.Value)
					}
				}
			}
			$xmlNodeReader = [System.Xml.XmlNodeReader]::new($xmlDocument)
			$writerSettings = $xslt.OutputSettings.Clone()
			$xmlWriter = [System.Xml.XmlWriter]::Create($htmlOutputPath, $writerSettings)
			try {
				Write-Stage -Group Write -Message "Writing HTML '$htmlOutputPath'."
				$xslt.Transform($xmlNodeReader, $xsltArgs, $xmlWriter)
			}
			finally {
				$xmlWriter.Dispose()
				$xmlNodeReader.Dispose()
			}
			$matchRow.ActualRenderer = 'Generated'
		}
		$matchRow.HtmlPath = $htmlOutputPath

		$processedCount++
		Write-Stage -Group Done -Message "HTML created for '$($xmlFile.Name)'."

		if ($shouldPrintPdf) {
			Write-Stage -Group Pdf -Message "Generating PDF '$pdfOutputPath'."
			Convert-HtmlToPdf -BrowserPath $pdfBrowser -HtmlPath $htmlOutputPath -PdfPath $pdfOutputPath
			$pdfCount++
			$matchRow.PdfPath = $pdfOutputPath
			Write-Stage -Group Pdf -Message "PDF created '$pdfOutputPath'."
		}
	}
	catch {
		$matchRow.Error = $_.Exception.Message
		$failedCopyPath = Copy-FailedInfoPathFile -XmlFile $xmlFile -SourceRoot $InfoPathDirectory -FailureRoot $FailedFilesDirectory
		$failedCount++
		Write-ErrorLogEntry -ErrorLogEntries $errorLogEntries -SourceFile $xmlFile.FullName -Message "$($_.Exception.Message) Copied to '$failedCopyPath'."
		Write-Stage -Group Warn -Message "Failed to process '$($xmlFile.FullName)'. Copied to '$failedCopyPath'."
		Write-Stage -Group Error -Message $_.Exception.Message
	}
}

if ($errorLogEntries.Count -eq 0) {
	$errorLogEntries.Add("[$(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')] No processing errors.") | Out-Null
}

$errorLogEntries | Set-Content -LiteralPath $ErrorLogPath -Encoding UTF8
$xsnMatches | Export-Csv -LiteralPath (Join-Path -Path $OutputDirectory -ChildPath 'InfoPathXsnMatches.csv') -NoTypeInformation -Encoding UTF8
Write-Stage -Group Done -Message "XML files processed to HTML: $processedCount"
Write-Stage -Group Done -Message "Output folder: $OutputDirectory"
Write-Stage -Group Warn -Message "Failed files: $failedCount"
Write-Stage -Group Warn -Message "Failed file copy folder: $FailedFilesDirectory"
Write-Stage -Group Write -Message "Error log: $ErrorLogPath"

if ($shouldPrintPdf) {
	Write-Stage -Group Pdf -Message "PDF files generated: $pdfCount"
}
if ($failedCount -gt 0) {
	throw "HTML/PDF rendering failed for $failedCount file(s). See '$ErrorLogPath'."
}
