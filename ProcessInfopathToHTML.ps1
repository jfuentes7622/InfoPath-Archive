function Write-Stage {
	param(
		[Parameter(Mandatory = $true)]
		[string]$Message,

		[ValidateSet("Init", "Input", "Resolve", "Build", "Write", "Pdf", "Done", "Warn", "Error")]
		[string]$Group = "Build"
	)

	$color = switch ($Group) {
		"Init" { "Cyan" }
		"Input" { "DarkCyan" }
		"Resolve" { "Yellow" }
		"Build" { "White" }
		"Write" { "Green" }
		"Pdf" { "Magenta" }
		"Done" { "Blue" }
		"Warn" { "DarkYellow" }
		"Error" { "Red" }
		default { "White" }
	}

	Write-Host "[$Group] $Message" -ForegroundColor $color
}

function Convert-ToBooleanValue {
	param(
		[Parameter(Mandatory = $true)]
		[string]$Value,

		[string]$ParameterName = "PrintToPdf"
	)

	$normalized = $Value.Trim().ToLowerInvariant()
	switch ($normalized) {
		"1" { return $true }
		"0" { return $false }
		"true" { return $true }
		"false" { return $false }
		"yes" { return $true }
		"no" { return $false }
		default {
			throw "$ParameterName must be one of: yes, no, true, false, 1, 0"
		}
	}
}

function Get-RelativePath {
	param(
		[Parameter(Mandatory = $true)]
		[string]$BasePath,
		[Parameter(Mandatory = $true)]
		[string]$FullPath
	)

	# Normalize paths to absolute form
	$basePath = [System.IO.Path]::GetFullPath($BasePath).TrimEnd(
		[System.IO.Path]::DirectorySeparatorChar,
		[System.IO.Path]::AltDirectorySeparatorChar
	)
	$fullPath = [System.IO.Path]::GetFullPath($FullPath)

	# Use Uri to calculate relative path (compatible with .NET Framework)
	try {
		$baseUri = New-Object Uri($basePath + [System.IO.Path]::DirectorySeparatorChar)
		$fullUri = New-Object Uri($fullPath)
		$relativeUri = $baseUri.MakeRelativeUri($fullUri)
		$relativePath = [System.Uri]::UnescapeDataString($relativeUri.ToString()).Replace('/', [System.IO.Path]::DirectorySeparatorChar)
		return $relativePath
	}
	catch {
		# Fallback for edge cases
		return $fullPath
	}
}

function Convert-ToXsltParamName {
	param(
		[Parameter(Mandatory = $true)]
		[string]$Name
	)

	$sanitized = ($Name -replace "[^A-Za-z0-9_]", "_")
	if ($sanitized -match "^[0-9]") {
		$sanitized = "_$sanitized"
	}

	return "meta_$sanitized"
}

function Find-PdfBrowser {
	$candidates = @(
		"$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe",
		"${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe",
		"$env:LOCALAPPDATA\Microsoft\Edge\Application\msedge.exe",
		"$env:ProgramFiles\Google\Chrome\Application\chrome.exe",
		"${env:ProgramFiles(x86)}\Google\Chrome\Application\chrome.exe",
		"$env:LOCALAPPDATA\Google\Chrome\Application\chrome.exe"
	)

	foreach ($candidate in $candidates) {
		if (-not [string]::IsNullOrWhiteSpace($candidate) -and (Test-Path -LiteralPath $candidate -PathType Leaf)) {
			return $candidate
		}
	}

	return $null
}

function Convert-HtmlToPdf {
	param(
		[Parameter(Mandatory = $true)]
		[string]$BrowserPath,

		[Parameter(Mandatory = $true)]
		[string]$HtmlPath,

		[Parameter(Mandatory = $true)]
		[string]$PdfPath
	)

	$temporaryDirectory = Join-Path -Path ([System.IO.Path]::GetTempPath()) -ChildPath ("InfoPath PDF-" + [guid]::NewGuid().ToString('N'))
	$profileDirectory = Join-Path -Path $temporaryDirectory -ChildPath 'Browser Profile'
	$temporaryPdfPath = Join-Path -Path $temporaryDirectory -ChildPath 'Rendered Form.pdf'
	$process = $null

	try {
		New-Item -Path $profileDirectory -ItemType Directory -Force | Out-Null
		$htmlUri = [System.Uri]::new([System.IO.Path]::GetFullPath($HtmlPath)).AbsoluteUri
		# Start-Process joins ArgumentList into a command line, so quote path values explicitly.
		$arguments = @(
			'--headless',
			'--disable-gpu',
			'--no-first-run',
			'--no-default-browser-check',
			'--disable-extensions',
			'--no-pdf-header-footer',
			"--user-data-dir=`"$profileDirectory`"",
			"--print-to-pdf=`"$temporaryPdfPath`"",
			"`"$htmlUri`""
		)

		$process = Start-Process -FilePath $BrowserPath -ArgumentList $arguments -Wait -PassThru -NoNewWindow
		if ($process.ExitCode -ne 0) {
			throw "PDF generation failed for '$HtmlPath': browser exited with code $($process.ExitCode)."
		}
		if (-not (Test-Path -LiteralPath $temporaryPdfPath -PathType Leaf)) {
			throw "PDF generation failed for '$HtmlPath': browser did not create a PDF."
		}

		$stream = [System.IO.File]::OpenRead($temporaryPdfPath)
		try {
			if ($stream.Length -lt 10) {
				throw "PDF generation failed for '$HtmlPath': generated PDF is empty or truncated."
			}
			$header = New-Object byte[] 5
			$null = $stream.Read($header, 0, $header.Length)
			$tail = New-Object byte[] ([int][Math]::Min(1024, $stream.Length))
			$null = $stream.Seek(-$tail.Length, [System.IO.SeekOrigin]::End)
			$null = $stream.Read($tail, 0, $tail.Length)
			if ([System.Text.Encoding]::ASCII.GetString($header) -ne '%PDF-' -or
				-not [System.Text.Encoding]::ASCII.GetString($tail).Contains('%%EOF')) {
				throw "PDF generation failed for '$HtmlPath': generated file has an invalid PDF signature or missing end marker."
			}
		}
		finally {
			$stream.Dispose()
		}

		# Publish only the new validated PDF; an older destination cannot count as success.
		Move-Item -LiteralPath $temporaryPdfPath -Destination $PdfPath -Force
	}
	finally {
		if ($null -ne $process) {
			$process.Dispose()
		}
		if (Test-Path -LiteralPath $temporaryDirectory -PathType Container) {
			Remove-Item -LiteralPath $temporaryDirectory -Recurse -Force
		}
	}
}

function New-MetadataIndex {
	param(
		[Parameter(Mandatory = $true)]
		[object[]]$Rows
	)

	$index = @{}

	foreach ($row in $Rows) {
		$props = $row.PSObject.Properties.Name

		foreach ($fullPathColumn in @("SourceFilePath", "FilePath", "Path", "FullName")) {
			if ($props -contains $fullPathColumn) {
				$fullPath = [string]$row.$fullPathColumn
				if (-not [string]::IsNullOrWhiteSpace($fullPath)) {
					$key = "FULL::$($fullPath.ToLowerInvariant())"
					if (-not $index.ContainsKey($key)) {
						$index[$key] = $row
					}
				}
			}
		}

		foreach ($nameColumn in @("FileName", "SourceFileName", "FileLeafRef", "Name")) {
			if ($props -contains $nameColumn) {
				$nameValue = [string]$row.$nameColumn
				if (-not [string]::IsNullOrWhiteSpace($nameValue)) {
					$key = "NAME::$($nameValue.ToLowerInvariant())"
					if (-not $index.ContainsKey($key)) {
						$index[$key] = $row
					}
				}
			}
		}
	}

	return $index
}

function Resolve-MetadataRow {
